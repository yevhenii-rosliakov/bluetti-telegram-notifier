"""State: tokens, gateway, last device state, outage history.

Two backends with the same schema and queries:

- SQLite in ``STATE_DIR`` (default). The standard-library ``sqlite3`` module is used
  directly: the database is a small local file and every statement finishes in
  microseconds, so it does not need a thread pool. WAL mode lets ``login`` run in a second
  process (e.g. ``kubectl exec``) while the service is running.
- PostgreSQL when ``DATABASE_URL`` is set (needs the ``postgres`` extra, ``psycopg``). Calls
  are synchronous like SQLite's: a handful of tiny statements per poll. A dropped
  connection is reopened and the statement retried once.

Every write is a single autocommitted statement, so it is atomic on both backends.
Timestamps are stored as UTC ISO strings and compare correctly as text (``COLLATE "C"`` on
PostgreSQL, where the default collation may not be byte order).
"""

from __future__ import annotations

import json
import logging
import os
import sqlite3
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import TYPE_CHECKING, Any, Protocol

from .detector import DeviceState

if TYPE_CHECKING:
    import psycopg

log = logging.getLogger(__name__)

Row = Mapping[str, Any]

_SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS kv (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS device_state (
    sn         TEXT PRIMARY KEY,
    state      TEXT NOT NULL,
    raw        TEXT,
    polled_at  TEXT
);
CREATE TABLE IF NOT EXISTS outages (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    sn              TEXT NOT NULL,
    start_at        TEXT NOT NULL,
    start_earliest  TEXT,
    end_at          TEXT,
    end_earliest    TEXT
);
CREATE INDEX IF NOT EXISTS outages_sn_start ON outages (sn, start_at);
"""

_POSTGRES_SCHEMA = """
CREATE TABLE IF NOT EXISTS kv (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS device_state (
    sn         TEXT PRIMARY KEY,
    state      TEXT NOT NULL,
    raw        TEXT,
    polled_at  TEXT COLLATE "C"
);
CREATE TABLE IF NOT EXISTS outages (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sn              TEXT NOT NULL,
    start_at        TEXT COLLATE "C" NOT NULL,
    start_earliest  TEXT COLLATE "C",
    end_at          TEXT COLLATE "C",
    end_earliest    TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS outages_sn_start ON outages (sn, start_at);
"""


class StorageError(Exception):
    """The database cannot be opened; the message is meant for the user."""


class _Db(Protocol):
    """One connection; SQL uses ``?`` placeholders."""

    def query(self, sql: str, params: Sequence[Any] = ()) -> list[Row]: ...

    def execute(self, sql: str, params: Sequence[Any] = ()) -> None: ...

    def close(self) -> None: ...


def _dict_row(cursor: sqlite3.Cursor, row: tuple[Any, ...]) -> dict[str, Any]:
    return {col[0]: value for col, value in zip(cursor.description, row, strict=True)}


class _Sqlite:
    def __init__(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists():
            # Create it private before SQLite opens it: it holds the refresh token.
            fd = os.open(path, os.O_CREAT | os.O_WRONLY, 0o600)
            os.close(fd)
        self._conn = sqlite3.connect(path, isolation_level=None, timeout=10)
        self._conn.row_factory = _dict_row
        self._conn.execute("PRAGMA journal_mode=WAL")
        self._conn.execute("PRAGMA synchronous=NORMAL")
        self._conn.executescript(_SQLITE_SCHEMA)

    def query(self, sql: str, params: Sequence[Any] = ()) -> list[Row]:
        rows: list[Row] = self._conn.execute(sql, params).fetchall()
        return rows

    def execute(self, sql: str, params: Sequence[Any] = ()) -> None:
        self._conn.execute(sql, params)

    def close(self) -> None:
        self._conn.close()


class _Postgres:
    def __init__(self, url: str, user: str | None = None, password: str | None = None) -> None:
        try:
            import psycopg  # noqa: PLC0415 - optional dependency
        except ImportError as exc:
            raise StorageError(
                "DATABASE_URL needs psycopg: pip install 'bluetti-grid-bot[postgres]'"
            ) from exc
        self._psycopg = psycopg
        # Given separately, they override the URL's own and need no percent-encoding.
        credentials = {k: v for k, v in (("user", user), ("password", password)) if v is not None}
        try:
            self._conninfo = psycopg.conninfo.make_conninfo(url, **credentials)
            self._conn = self._connect()
            self._conn.execute(_POSTGRES_SCHEMA)
        except psycopg.Error as exc:
            raise StorageError(f"Cannot connect to DATABASE_URL: {exc}") from exc

    def _connect(self) -> psycopg.Connection[dict[str, Any]]:
        from psycopg.rows import dict_row  # noqa: PLC0415 - optional dependency

        return self._psycopg.connect(
            self._conninfo, autocommit=True, row_factory=dict_row, connect_timeout=10
        )

    def _run(self, sql: str, params: Sequence[Any], fetch: bool) -> list[Row]:
        sql = sql.replace("?", "%s")
        for attempt in (1, 2):
            try:
                if self._conn.closed:
                    self._conn = self._connect()
                cur = self._conn.execute(sql, params)
                return list(cur.fetchall()) if fetch else []
            except self._psycopg.OperationalError as exc:
                # Reconnect and retry once if the connection dropped. Retrying a write is
                # safe: every write is an idempotent upsert, update or guarded insert.
                if attempt == 2 or not self._conn.broken:
                    raise
                log.warning("Database connection lost (%s); reconnecting", exc)
                self._conn.close()
        raise AssertionError("unreachable")  # pragma: no cover

    def query(self, sql: str, params: Sequence[Any] = ()) -> list[Row]:
        return self._run(sql, params, fetch=True)

    def execute(self, sql: str, params: Sequence[Any] = ()) -> None:
        self._run(sql, params, fetch=False)

    def close(self) -> None:
        self._conn.close()


@dataclass(frozen=True, slots=True)
class TokenSet:
    access_token: str | None
    refresh_token: str | None
    # Unix time; None = unknown (use until the API says it expired).
    expires_at: float | None
    obtained_at: float

    def to_json(self) -> str:
        return json.dumps(
            {
                "access_token": self.access_token,
                "refresh_token": self.refresh_token,
                "expires_at": self.expires_at,
                "obtained_at": self.obtained_at,
            }
        )

    @classmethod
    def from_json(cls, text: str) -> TokenSet:
        data = json.loads(text)
        return cls(
            access_token=data.get("access_token"),
            refresh_token=data.get("refresh_token"),
            expires_at=data.get("expires_at"),
            obtained_at=float(data.get("obtained_at") or 0),
        )


@dataclass(frozen=True, slots=True)
class Outage:
    id: int
    sn: str
    start: datetime
    start_earliest: datetime | None
    end: datetime | None
    end_earliest: datetime | None

    @property
    def approximate(self) -> bool:
        return self.start_earliest is not None or self.end_earliest is not None


def _ts(value: datetime | None) -> str | None:
    return None if value is None else value.isoformat()


def _dt(value: str | None) -> datetime | None:
    return None if value is None else datetime.fromisoformat(value)


class Storage:
    def __init__(self, db: _Db) -> None:
        self._db = db

    @classmethod
    def sqlite(cls, path: Path) -> Storage:
        try:
            return cls(_Sqlite(path))
        except (OSError, sqlite3.Error) as exc:
            raise StorageError(f"Cannot open {path}: {exc}") from exc

    @classmethod
    def postgres(cls, url: str, user: str | None = None, password: str | None = None) -> Storage:
        return cls(_Postgres(url, user, password))

    def close(self) -> None:
        self._db.close()

    def _one(self, sql: str, params: Sequence[Any] = ()) -> Row | None:
        rows = self._db.query(sql, params)
        return rows[0] if rows else None

    # key/value

    def get(self, key: str) -> str | None:
        row = self._one("SELECT value FROM kv WHERE key = ?", (key,))
        return None if row is None else str(row["value"])

    def set(self, key: str, value: str | None) -> None:
        if value is None:
            self._db.execute("DELETE FROM kv WHERE key = ?", (key,))
        else:
            self._db.execute(
                "INSERT INTO kv (key, value) VALUES (?, ?) "
                "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (key, value),
            )

    def get_tokens(self) -> TokenSet | None:
        text = self.get("tokens")
        return None if text is None else TokenSet.from_json(text)

    def save_tokens(self, tokens: TokenSet) -> None:
        self.set("tokens", tokens.to_json())

    def get_gateway(self) -> str | None:
        return self.get("gateway")

    def set_gateway(self, url: str | None) -> None:
        self.set("gateway", url)

    # device state

    def load_device(self, sn: str) -> tuple[DeviceState | None, dict[str, str], datetime | None]:
        row = self._one("SELECT state, raw, polled_at FROM device_state WHERE sn = ?", (sn,))
        if row is None:
            return None, {}, None
        state = DeviceState.from_dict(json.loads(row["state"]))
        raw: dict[str, str] = json.loads(row["raw"]) if row["raw"] else {}
        return state, raw, _dt(row["polled_at"])

    def save_device(
        self,
        state: DeviceState,
        raw: Mapping[str, str] | None = None,
        polled_at: datetime | None = None,
    ) -> None:
        """Save the detector state; ``raw``/``polled_at`` only replace the stored ones if given."""
        self._db.execute(
            "INSERT INTO device_state (sn, state, raw, polled_at) VALUES (?, ?, ?, ?) "
            "ON CONFLICT(sn) DO UPDATE SET state = excluded.state, "
            "raw = COALESCE(excluded.raw, device_state.raw), "
            "polled_at = COALESCE(excluded.polled_at, device_state.polled_at)",
            (
                state.sn,
                json.dumps(state.to_dict()),
                None if raw is None else json.dumps(dict(raw)),
                _ts(polled_at),
            ),
        )

    # outage history

    def _row_to_outage(self, row: Row) -> Outage:
        return Outage(
            id=int(row["id"]),
            sn=str(row["sn"]),
            start=datetime.fromisoformat(row["start_at"]),
            start_earliest=_dt(row["start_earliest"]),
            end=_dt(row["end_at"]),
            end_earliest=_dt(row["end_earliest"]),
        )

    def open_outage(self, sn: str) -> Outage | None:
        row = self._one(
            "SELECT * FROM outages WHERE sn = ? AND end_at IS NULL ORDER BY id DESC LIMIT 1",
            (sn,),
        )
        return None if row is None else self._row_to_outage(row)

    def start_outage(self, sn: str, start: datetime, start_earliest: datetime | None) -> None:
        """Record an outage start unless one is already open for this station."""
        self._db.execute(
            "INSERT INTO outages (sn, start_at, start_earliest) SELECT ?, ?, ? "
            "WHERE NOT EXISTS (SELECT 1 FROM outages WHERE sn = ? AND end_at IS NULL)",
            (sn, _ts(start), _ts(start_earliest), sn),
        )

    def end_outage(self, sn: str, end: datetime, end_earliest: datetime | None) -> None:
        self._db.execute(
            "UPDATE outages SET end_at = ?, end_earliest = ? WHERE sn = ? AND end_at IS NULL",
            (_ts(end), _ts(end_earliest), sn),
        )

    def history(self, limit: int, sns: list[str] | None = None) -> list[Outage]:
        query = "SELECT * FROM outages"
        params: list[Any] = []
        if sns:
            query += f" WHERE sn IN ({','.join('?' * len(sns))})"
            params += sns
        query += " ORDER BY start_at DESC, id DESC LIMIT ?"
        params.append(limit)
        return [self._row_to_outage(r) for r in self._db.query(query, params)]

    def outages_since(self, since: datetime, sns: list[str]) -> list[Outage]:
        """Outages of these stations that were still going on at or after ``since``."""
        if not sns:
            return []
        # Timestamps are stored as UTC ISO strings, so they compare correctly as text.
        query = "SELECT * FROM outages WHERE (end_at IS NULL OR end_at >= ?)"
        query += f" AND sn IN ({','.join('?' * len(sns))}) ORDER BY start_at, id"
        rows = self._db.query(query, [_ts(since.astimezone(UTC)), *sns])
        return [self._row_to_outage(r) for r in rows]
